#!/bin/sh
# Regenerates internal/reach/chnroutes.txt, the mainland China (CN) address ranges the cover-site
# check uses, from APNIC's public delegation statistics. Run it from the repository root:
#
#   scripts/gen-chnroutes.sh                    # downloads delegated-apnic-latest
#   scripts/gen-chnroutes.sh path/to/delegated  # uses a copy already downloaded
#
# Every IPv4 and IPv6 block APNIC lists as allocated or assigned to CN is kept. Adjacent IPv4
# blocks are merged, and each IPv4 run is written as the fewest CIDR prefixes that cover it.
set -eu

url=https://ftp.apnic.net/stats/apnic/delegated-apnic-latest
out=internal/reach/chnroutes.txt

if [ $# -ge 1 ]; then
	src=$1
else
	src=$(mktemp)
	trap 'rm -f "$src"' EXIT
	curl -fsSL --max-time 300 -o "$src" "$url"
fi

# The version line is "2|apnic|<serial>|...", and the serial is the file's date.
serial=$(awk -F'|' '!/^#/ && $1 ~ /^[0-9]/ { print $3; exit }' "$src")
case $serial in
[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]) ;;
*)
	echo "gen-chnroutes: $src does not look like a delegated-apnic file" >&2
	exit 1
	;;
esac

tmp=$(mktemp)
{
	echo "# Mainland China (CN) IPv4 and IPv6 ranges, allocated or assigned."
	echo "# Source: APNIC delegated statistics, $url"
	echo "# APNIC file date: $serial. Generated by scripts/gen-chnroutes.sh; do not edit by hand."

	# IPv4 records give a first address and an address count, which need not be a power of two.
	awk -F'|' '$2 == "CN" && $3 == "ipv4" && ($7 == "allocated" || $7 == "assigned") {
		split($4, o, ".")
		printf "%.0f %s\n", ((o[1] * 256 + o[2]) * 256 + o[3]) * 256 + o[4], $5
	}' "$src" | sort -n -k1,1 | awk '
	function emit(start, n,    size, bits) {
		while (n > 0) {
			size = 1; bits = 32
			while (size * 2 <= n && start % (size * 2) == 0) { size *= 2; bits-- }
			# %.0f, not %d: some awks print %d through a 32-bit signed int.
			printf "%.0f.%.0f.%.0f.%.0f/%d\n", int(start / 16777216) % 256, int(start / 65536) % 256,
				int(start / 256) % 256, start % 256, bits
			start += size; n -= size
		}
	}
	{
		if (have && $1 <= end) {
			if ($1 + $2 > end) end = $1 + $2
			next
		}
		if (have) emit(first, end - first)
		first = $1; end = $1 + $2; have = 1
	}
	END { if (have) emit(first, end - first) }'

	# IPv6 records give a prefix length already.
	awk -F'|' '$2 == "CN" && $3 == "ipv6" && ($7 == "allocated" || $7 == "assigned") { print $4 "/" $5 }' "$src"
} >"$tmp"

v4=$(grep -c '^[0-9]*\.' "$tmp" || true)
v6=$(grep -c '^[0-9a-f]*:' "$tmp" || true)
if [ "$v4" -lt 1000 ] || [ "$v6" -lt 100 ]; then
	echo "gen-chnroutes: only $v4 IPv4 and $v6 IPv6 ranges; refusing to write $out" >&2
	rm -f "$tmp"
	exit 1
fi
mv "$tmp" "$out"
echo "gen-chnroutes: wrote $v4 IPv4 and $v6 IPv6 ranges to $out (APNIC $serial)"
